package org.qntx.card;

import javacard.framework.JCSystem;
import javacard.security.AESKey;
import javacard.security.KeyAgreement;
import javacard.security.KeyBuilder;
import javacard.security.MessageDigest;
import javacard.security.RandomData;
import javacard.security.Signature;
import javacardx.crypto.Cipher;

/**
 * The shared engines and scratch arrays, allocated once in the applet constructor (architecture.md
 * §5.2). Commands are sequential, so one command owns all scratch; {@link #wipeScratch} runs in a
 * {@code finally} around every handler.
 *
 * <p>{@code P} (130 B) holds up to two uncompressed secp256k1 points. {@code W} (256 B) is the
 * arithmetic, KDF and DER scratch; shared regions inside it are {@link #W_DER} (72 B, DER encodings
 * of {@link Identity}) and {@link #W_KDF} (40 B, used by {@link Kdf#kdf108}). {@code H} (192 B) is
 * {@link Derivation}'s HMAC-SHA512 work area: {@code H[0..128)} the 128-byte pad block (0x36/0x5C
 * fill, key xored in) and {@code H[128..192)} the 64-byte inner digest. {@code N} (101 B) is the
 * working node: {@code N[0..64)} the current node {@code key(32) ‖ chain(32)} and {@code
 * N[64..101)} the 37-byte CKD input.
 *
 * <p>{@code seed} (64 B) is the session seed of §10.1 — decrypted into transient memory by VERIFY
 * or generated by CREATE, wiped by VERIFY step 1, ERASE and teardown. {@code secpCache} (170 B) and
 * {@code edCache} (105 B) are the derivation node caches of architecture.md §5.3: {@code path(41) ‖
 * key(32) ‖ chain(32) ‖ uncompressed parent public key(65)} for secp256k1 (uncompressed, so a warm
 * non-hardened leaf has {@code K_par} for the §16.2 item 6 public-derivation check without a
 * decompression), {@code path(41) ‖ key(32) ‖ chain(32)} for ed25519. Seed, caches and {@code
 * edStream} are session state: {@link #wipeScratch} does not touch them.
 */
final class Mem {
    /** {@link #W} offset of the 72-byte DER codec area used by {@link Identity}. */
    static final short W_DER = 184;

    /**
     * {@link #W} offset of the 40-byte area {@link Kdf#kdf108} uses for its CMAC separators at
     * {@code W_KDF + 36}; {@link Kdf#kdf} keeps no scratch, so two derivations in one command share
     * no temporary (§16.2 item 4).
     */
    static final short W_KDF = 216;

    final Cipher aesCbc;
    final Signature cmac;
    final MessageDigest sha256;
    final MessageDigest sha512;
    final RandomData random;
    final KeyAgreement plainXy;

    /** The shared {@code ALG_EC_PACE_GM} engine behind {@code s·G + H} (architecture.md §5.1). */
    final KeyAgreement paceGm;

    /** Transient wrap keys of §10.1: {@code kEnc ‖ kMac}, outputs of {@link Kdf#kdf108}. */
    final AESKey kEnc;

    final AESKey kMac;
    final byte[] P;
    final byte[] W;
    final byte[] seed;
    final byte[] H;
    final byte[] N;
    final byte[] secpCache;
    final byte[] edCache;

    /**
     * The Ed25519 stream of §9.11 (architecture.md §5.1): {@code a(32) ‖ r(32) ‖ R(65) ‖ A(65)},
     * the scalars big-endian and the points uncompressed {@code 04 ‖ X ‖ Y}. Session state, not
     * scratch: wiped by {@code Session.endPending} and teardown.
     */
    final byte[] edStream;

    /**
     * The pending export/import encryption and MAC keys of §9.13–§9.14 and the 16-byte pending
     * sender card ID (architecture.md §5.1 {@code Transfer} row). Session state like {@link
     * #edStream}: wiped by {@code Session.endPending} and teardown, never by {@link #wipeScratch}.
     */
    final AESKey kTe;

    final AESKey kTm;
    final byte[] sender;

    Mem() {
        aesCbc = Cipher.getInstance(Cipher.ALG_AES_BLOCK_128_CBC_NOPAD, false);
        cmac = Signature.getInstance(Signature.ALG_AES_CMAC_128, false);
        sha256 = MessageDigest.getInstance(MessageDigest.ALG_SHA_256, false);
        sha512 = MessageDigest.getInstance(MessageDigest.ALG_SHA_512, false);
        random = RandomData.getInstance(RandomData.ALG_KEYGENERATION);
        plainXy = KeyAgreement.getInstance(KeyAgreement.ALG_EC_SVDP_DH_PLAIN_XY, false);
        paceGm = KeyAgreement.getInstance(KeyAgreement.ALG_EC_PACE_GM, false);
        kEnc = aesKey();
        kMac = aesKey();
        P = JCSystem.makeTransientByteArray((short) 130, JCSystem.CLEAR_ON_DESELECT);
        W = JCSystem.makeTransientByteArray((short) 256, JCSystem.CLEAR_ON_DESELECT);
        seed = JCSystem.makeTransientByteArray((short) 64, JCSystem.CLEAR_ON_DESELECT);
        H = JCSystem.makeTransientByteArray((short) 192, JCSystem.CLEAR_ON_DESELECT);
        N = JCSystem.makeTransientByteArray((short) 101, JCSystem.CLEAR_ON_DESELECT);
        secpCache = JCSystem.makeTransientByteArray((short) 170, JCSystem.CLEAR_ON_DESELECT);
        edCache = JCSystem.makeTransientByteArray((short) 105, JCSystem.CLEAR_ON_DESELECT);
        edStream = JCSystem.makeTransientByteArray((short) 194, JCSystem.CLEAR_ON_DESELECT);
        kTe = aesKey();
        kTm = aesKey();
        sender = JCSystem.makeTransientByteArray((short) 16, JCSystem.CLEAR_ON_DESELECT);
    }

    private static AESKey aesKey() {
        return (AESKey)
                KeyBuilder.buildKey(
                        KeyBuilder.TYPE_AES_TRANSIENT_DESELECT, KeyBuilder.LENGTH_AES_128, false);
    }

    /** Resets the shared SHA-512 engine through a woven call the fault tests can count. */
    void resetSha512() {
        sha512.reset();
    }

    /**
     * Per-command scratch only: {@code P}, {@code W}, {@code H}, {@code N} and the wrap keys
     * (overwritten, never {@code clearKey}; architecture.md §4). Session state — {@code seed} and
     * the caches — is wiped by its owners and by teardown, not here.
     */
    void wipeScratch() {
        Bytes.wipe(P, (short) 0, (short) P.length);
        Bytes.wipe(W, (short) 0, (short) W.length);
        Bytes.wipe(H, (short) 0, (short) H.length);
        Bytes.wipe(N, (short) 0, (short) N.length);
        kEnc.setKey(Const.ZEROS, (short) 0);
        kMac.setKey(Const.ZEROS, (short) 0);
    }
}
