    @Test
    void wrapVectors() throws Exception {
        Map<String, Object> d = json("wrap.json");
        byte[] wrapLabel = h(d.get("wrapLabel"));
        byte[] fpLabel = h(d.get("fingerprintLabel"));
        for (Map<String, Object> c : list(d, "cases")) {
            byte[] keys = H3.kdf108(h(c.get("wrapKey")), wrapLabel, h(c.get("accessHash")));
            assertArrayEquals(h(c.get("kEnc")), Arrays.copyOfRange(keys, 0, 16), "kEnc");
            assertArrayEquals(h(c.get("kMac")), Arrays.copyOfRange(keys, 16, 32), "kMac");
            byte[] ct = H3.cbcEnc(h(c.get("kEnc")), H3.zeros(16), h(c.get("seed")));
            assertArrayEquals(h(c.get("ct")), ct, "ct " + c.get("name"));
            assertArrayEquals(
                    h(c.get("tag")), H3.cmac(h(c.get("kMac")), ct), "tag " + c.get("name"));
            assertArrayEquals(
                    h(c.get("fp")),
                    H3.sha256(H3.cat(fpLabel, h(c.get("seed")))),
                    "fp " + c.get("name"));
        }
    }

    // ---------------------------------------------------------------- §9.13–9.14 transfer

    @Test
    void transferVectors() throws Exception {
        Map<String, Object> d = json("transfer.json");
        Map<String, Object> labels = (Map<String, Object>) d.get("labels");
        byte[] offerLabel = h(labels.get("offer"));
        byte[] kdfLabel = h(labels.get("kdfTransfer"));

        for (Map<String, Object> c : list(d, "decompress")) {
            byte[] got = H3.decompress(h(c.get("compressed")));
            if ((Boolean) c.get("valid")) {
                assertArrayEquals(h(c.get("uncompressed")), got, "decompress " + c.get("name"));
            } else {
                assertNull(got, "decompress should reject " + c.get("name"));
            }
        }

        for (Map<String, Object> t : list(d, "transfers")) {
            String name = (String) t.get("name");
            byte[] aS = h(card(d, (String) t.get("source")).get("A"));
            byte[] aT = h(card(d, (String) t.get("target")).get("A"));
            byte[] lk = h(t.get("LK"));
            byte[] e = h(t.get("E"));
            // the offer hash and sig_T under the target's identity (§9.12)
            assertArrayEquals(
                    h(t.get("offerHash")), H3.sha256(H3.cat(offerLabel, lk)), "offerHash " + name);
            assertTrue(
                    H3.ecdsaVerify(
                            H3.decompress(aT), h(t.get("offerHash")), h(t.get("offerSignature"))),
                    "sig_T " + name);
            // M, TH and both directions of Z (§9.13–9.14)
            byte[] m = H3.cat(H3.label("qntx-card/v1/export"), aS, aT, lk, e);
            assertArrayEquals(h(t.get("M")), m, "M " + name);
            byte[] th = H3.sha256(m);
            assertArrayEquals(h(t.get("TH")), th, "TH " + name);
            byte[] zSender = H3.ecdhX(H3.bigInt(h(t.get("e"))), lk);
            byte[] zTarget = H3.ecdhX(H3.bigInt(h(t.get("linkPrivate"))), e);
            assertArrayEquals(h(t.get("Z")), zSender, "Z via e·LK " + name);
            assertArrayEquals(h(t.get("Z")), zTarget, "Z via l·E " + name);
            assertTrue(
                    H3.ecdsaVerify(H3.decompress(aS), th, h(t.get("exportSignature"))),
                    "sig_S " + name);
            // the transfer keys and the sealed payload (§9.13 P1 = 0x01)
            byte[] keys = H3.kdf(zSender, kdfLabel, th, 32);
            byte[] kTe = Arrays.copyOfRange(keys, 0, 16);
            byte[] kTm = Arrays.copyOfRange(keys, 16, 32);
            assertArrayEquals(h(t.get("kTe")), kTe, "kTe " + name);
            assertArrayEquals(h(t.get("kTm")), kTm, "kTm " + name);
            byte[] sealed = Peer3.seal(kTe, kTm, h(t.get("payload")));
            byte[] ct = Arrays.copyOf(sealed, sealed.length - 16);
            byte[] tag = Arrays.copyOfRange(sealed, sealed.length - 16, sealed.length);
            assertArrayEquals(h(t.get("ct")), ct, "ct " + name);
            assertArrayEquals(h(t.get("tag")), tag, "tag " + name);
            assertArrayEquals(
                    h(t.get("payload")),
                    Peer3.unseal(kTe, kTm, H3.cat(h(t.get("ct")), h(t.get("tag")))),
                    "unseal " + name);
        }
    }

    @SuppressWarnings("unchecked")
    private static Map<String, Object> card(Map<String, Object> d, String name) {
        for (Map<String, Object> c : (List<Map<String, Object>>) d.get("cards")) {
            if (name.equals(c.get("name"))) {
                return c;
            }
        }
        throw new IllegalArgumentException("no card " + name);
    }

    // ---------------------------------------------------------------- §10.2–10.3 derivation

    @Test
    void bip32Vectors() throws Exception {
        Map<String, Object> d = json("derivation.json");
        for (Map<String, Object> v : list(d, "bip32")) {
            byte[] seed = h(v.get("seed"));
            for (Map<String, Object> n : list(v, "nodes")) {
                long[] path = parsePath((String) n.get("path"));
                byte[][] node = H3.derivePriv(seed, path);
                assertArrayEquals(
                        h(n.get("privateKey")),
                        node[0],
                        "key " + v.get("name") + " " + n.get("path"));
                assertArrayEquals(
                        h(n.get("chainCode")),
                        node[1],
                        "chain " + v.get("name") + " " + n.get("path"));
                assertArrayEquals(
                        h(n.get("publicKey")),
                        node[2],
                        "pub " + v.get("name") + " " + n.get("path"));
            }
        }
        // §10.2: the master key is valid iff int(I_L) ∈ [1, n − 1]
        for (Map<String, Object> m : list(d, "invalidMaster")) {
            BigInteger k = H3.bigInt(h(m.get("il")));
            boolean valid = k.signum() > 0 && k.compareTo(H3.N) < 0;
            assertEquals((Boolean) m.get("valid"), valid, "master " + m.get("name"));
        }
        // §10.3: the child is invalid iff int(I_L) ≥ n or (I_L + k_par) mod n = 0 (6A80)
        for (Map<String, Object> c : list(d, "invalidChild")) {
            BigInteger il = H3.bigInt(h(c.get("il")));
            BigInteger k = il.add(H3.bigInt(h(c.get("parentKey")))).mod(H3.N);
            boolean valid = il.compareTo(H3.N) < 0 && k.signum() != 0;
            assertEquals((Boolean) c.get("valid"), valid, "child " + c.get("name"));
            if (valid) {
                assertArrayEquals(h(c.get("childKey")), H3.u256(k), "childKey " + c.get("name"));
            }
        }
        // templates: the wallet master public key and a hardened template path
        Map<String, Object> templates = (Map<String, Object>) d.get("templates");
        byte[] tseed = h(templates.get("seed"));
        assertArrayEquals(
                h(templates.get("masterPublicKey")), H3.masterPublicKey(tseed), "masterPublicKey");
        for (Map<String, Object> n : list(templates, "secp256k1")) {
            long[] path = parsePath((String) n.get("path"));
            byte[][] node = H3.derivePriv(tseed, path);
            assertArrayEquals(h(n.get("privateKey")), node[0], "tpl key " + n.get("name"));
            assertArrayEquals(h(n.get("publicKey")), node[2], "tpl pub " + n.get("name"));
        }
    }

    private static long[] parsePath(String path) {
        if (path.equals("m")) {
            return new long[0];
        }
        String[] parts = path.substring(2).split("/");
        long[] out = new long[parts.length];
        for (int i = 0; i < parts.length; i++) {
            boolean hardened = parts[i].endsWith("'");
            long v =
                    Long.parseLong(
                            hardened ? parts[i].substring(0, parts[i].length() - 1) : parts[i]);
            out[i] = hardened ? v + 0x80000000L : v;
        }
        return out;
    }

    // ---------------------------------------------------------------- BouncyCastle oracle

    @Test
    void bouncyCastleCrossCheck() {
        // H3 signs, BouncyCastle verifies; BouncyCastle signs (not independently: same engine)
        // — the actual cross-check is H3's verify against an independently built key pair and
        // H3's §10.5 decompression against the curve's own decoder.
        BigInteger d = H3.randomScalar();
        byte[] uncompressed = H3.pubPoint(d);
        byte[] compressed = H3.compress(H3.point(uncompressed));
        assertArrayEquals(
                uncompressed, H3.decompress(compressed), "§10.5 decompress vs curve decode");
        assertArrayEquals(
                uncompressed,
                org.bouncycastle.asn1.sec.SECNamedCurves.getByName("secp256k1")
                        .getCurve()
                        .decodePoint(compressed)
                        .normalize()
                        .getEncoded(false),
                "curve decodePoint");

        byte[] hash = H3.sha256(H3.label("cross-check"));
        byte[] sig = H3.ecdsaSign(d, hash);
        assertTrue(H3.ecdsaVerify(uncompressed, hash, sig), "own sign→verify");
        // independently: BouncyCastle verifies H3's signature under a fresh parameter object
        ECDomainParameters domain =
                new ECDomainParameters(
                        org.bouncycastle.asn1.sec.SECNamedCurves.getByName("secp256k1").getCurve(),
                        org.bouncycastle.asn1.sec.SECNamedCurves.getByName("secp256k1").getG(),
                        org.bouncycastle.asn1.sec.SECNamedCurves.getByName("secp256k1").getN());
        ECDSASigner v = new ECDSASigner();
        v.init(
                false,
                new ECPublicKeyParameters(domain.getCurve().decodePoint(uncompressed), domain));
        BigInteger r = H3.bigInt(Arrays.copyOfRange(sig, 0, 32));
        BigInteger s = H3.bigInt(Arrays.copyOfRange(sig, 32, 64));
        assertTrue(v.verifySignature(hash, r, s), "BC verifies H3 signature");
        // and rejects a tampered one
        sig[63] ^= 1;
        assertFalse(H3.ecdsaVerify(uncompressed, hash, sig), "tampered signature rejected");
    }
