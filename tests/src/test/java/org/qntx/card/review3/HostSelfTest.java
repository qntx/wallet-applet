    @Test
    void kdfVectors() throws Exception {
        Map<String, Object> d = json("kdf.json");
        for (Map<String, Object> c : list(d, "cmac")) {
            assertArrayEquals(
                    h(c.get("tag")), H3.cmac(h(c.get("key")), h(c.get("message"))), "cmac case");
        }
        for (Map<String, Object> c : list(d, "kdf")) {
            byte[] out =
                    H3.kdf(
                            h(c.get("z")),
                            h(c.get("label")),
                            h(c.get("ctx")),
                            ((Number) c.get("len")).intValue());
            assertArrayEquals(h(c.get("out")), out, "kdf case");
        }
        for (Map<String, Object> c : list(d, "kdf108")) {
            assertArrayEquals(
                    h(c.get("out")),
                    H3.kdf108(h(c.get("key")), h(c.get("label")), h(c.get("ctx"))),
                    "kdf108 case");
        }
    }

    @Test
    void m2PadUnpad() {
        // §1: M2 pads with 0x80 then zeros to a 16 multiple; a full block is appended when the
        // input already is a multiple of 16 (record.json's 32-byte padding block exercises this).
        for (int len = 0; len <= 48; len++) {
            byte[] x = new byte[len];
            for (int i = 0; i < len; i++) {
                x[i] = (byte) (i + 1);
            }
            byte[] padded = H3.m2(x);
            assertEquals(0, padded.length % 16);
            assertTrue(padded.length > len);
            assertArrayEquals(x, H3.unM2(padded));
        }
        assertNull(H3.unM2(new byte[0]));
        assertNull(H3.unM2(new byte[15]));
        assertNull(H3.unM2(new byte[17]));
        byte[] bad = H3.m2(new byte[] {1, 2, 3});
        bad[3] = 0; // clobber the 0x80 marker: no 0x80 follows the last nonzero byte
        assertNull(H3.unM2(bad));
        byte[] noMarker = new byte[16];
        assertNull(H3.unM2(noMarker));
    }

