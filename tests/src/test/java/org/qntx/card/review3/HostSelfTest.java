    @Test
    void certVectors() throws Exception {
        Map<String, Object> d = json("cert.json");
        for (Map<String, Object> id : list(d, "identities")) {
            byte[] pub = h(id.get("public"));
            byte[] compressed = h(id.get("compressed"));
            assertArrayEquals(compressed, H3.compress(H3.point(pub)), "compress " + id.get("name"));
            assertArrayEquals(h(id.get("id")), H3.cardId(compressed), "ID " + id.get("name"));
        }
        for (Map<String, Object> v : list(d, "verify")) {
            byte[] anchor = h(v.get("anchor"));
            byte[] cert = h(v.get("cert"));
            byte[] a = Arrays.copyOfRange(cert, 0, 33);
            byte[] sig = Arrays.copyOfRange(cert, 33, 97);
            boolean ok =
                    H3.ecdsaVerify(
                            anchor, H3.sha256(H3.cat(H3.label("qntx-card/v1/cert"), a)), sig);
            assertEquals((Boolean) v.get("valid"), ok, "cert verify " + v.get("name"));
        }
    }

    // ---------------------------------------------------------------- §8 session / records

    @Test
    void sessionVectors() throws Exception {
        Map<String, Object> d = json("session.json");
        byte[] hostEph = h(d.get("hostEph"));
        byte[] cardEph = h(d.get("cardEph"));
        Map<String, Object> identity = (Map<String, Object>) d.get("identity");
        byte[] a = h(identity.get("compressed"));
        byte[] transcript = H3.cat(H3.label("qntx-card/v1/session"), hostEph, cardEph, a);
        byte[] th = H3.sha256(transcript);
        assertArrayEquals(h(d.get("th")), th, "TH");
        // the card's session signature verifies under A over TH (§8.1)
        assertTrue(H3.ecdsaVerify(H3.decompress(a), th, h(d.get("sig"))), "session signature");
        // the host's Z from its ephemeral private key (§8.1)
        byte[] z = H3.ecdhX(H3.bigInt(h(d.get("hostPrivate"))), cardEph);
        assertArrayEquals(h(d.get("z")), z, "Z");
        byte[] keys = H3.kdf(z, h(d.get("kdfLabel")), th, 64);
        assertArrayEquals(h(d.get("kce")), Arrays.copyOfRange(keys, 0, 16), "K_ce");
        assertArrayEquals(h(d.get("kcm")), Arrays.copyOfRange(keys, 16, 32), "K_cm");
        assertArrayEquals(h(d.get("kre")), Arrays.copyOfRange(keys, 32, 48), "K_re");
        assertArrayEquals(h(d.get("krm")), Arrays.copyOfRange(keys, 48, 64), "K_rm");
    }

    @Test
    void recordVectors() throws Exception {
        Map<String, Object> d = json("record.json");
        Map<String, Object> keys = (Map<String, Object>) d.get("keys");
        byte[] kce = h(keys.get("kce"));
        byte[] kcm = h(keys.get("kcm"));
        byte[] kre = h(keys.get("kre"));
        byte[] krm = h(keys.get("krm"));

        // §8.3 command records: wrap produces the exact APDU, and the tampered ones are
        // rejected by tag or padding checks.
        for (Map<String, Object> c : list(d, "commands")) {
            int ctr = ((Number) c.get("ctr")).intValue();
            // §8.3: plain = INS ‖ P1 ‖ P2 ‖ data — a deliberately short plain (the
            // two-byte inner-6700 case) simply contributes fewer fields
            byte[] plain =
                    H3.cat(h(c.get("ins")), h(c.get("p1")), h(c.get("p2")), h(c.get("data")));
            byte[] iv = H3.aesBlock(kce, H3.cat(new byte[] {1}, H3.zeros(13), H3.u16(ctr)));
            assertArrayEquals(h(c.get("iv")), iv, "iv " + c.get("name"));
            byte[] ct = H3.cbcEnc(kce, iv, H3.m2(plain));
            byte[] tag = Arrays.copyOf(H3.cmac(kcm, H3.cat(H3.u16(ctr), ct)), 8);
            byte[] apdu =
                    H3.cat(
                            new byte[] {(byte) 0x80, (byte) 0x12, 0, 0, (byte) (ct.length + 8)},
                            ct,
                            tag,
                            new byte[] {0});
            assertArrayEquals(h(c.get("apdu")), apdu, "apdu " + c.get("name"));
        }
        for (Map<String, Object> r : list(d, "responses")) {
            int ctr = ((Number) r.get("ctr")).intValue();
            // the rapdu carries the record ct ‖ tag followed by the outer SW 9000
            byte[] rapdu = h(r.get("rapdu"));
            byte[] body = Arrays.copyOf(rapdu, rapdu.length - 2);
            byte[] ct = Arrays.copyOf(body, body.length - 8);
            byte[] tag = Arrays.copyOfRange(body, body.length - 8, body.length);
            byte[] expected = Arrays.copyOf(H3.cmac(krm, H3.cat(H3.u16(ctr), ct)), 8);
            assertTrue(H3.equal(expected, tag), "response tag " + r.get("name"));
            byte[] iv = H3.aesBlock(kre, H3.cat(new byte[] {2}, H3.zeros(13), H3.u16(ctr)));
            byte[] plain = H3.unM2(H3.cbcDec(kre, iv, ct));
            assertNotNull(plain, "response unM2 " + r.get("name"));
            byte[] data = Arrays.copyOf(plain, plain.length - 2);
            int sw = ((plain[plain.length - 2] & 0xFF) << 8) | (plain[plain.length - 1] & 0xFF);
            assertArrayEquals(h(r.get("data")), data, "response data " + r.get("name"));
            assertEquals(
                    Integer.parseInt((String) r.get("sw"), 16), sw, "response sw " + r.get("name"));
        }
        for (Map<String, Object> c : list(d, "rejectedCommands")) {
            int ctr = ((Number) c.get("ctr")).intValue();
            byte[] apdu = h(c.get("apdu"));
            byte[] body = Arrays.copyOfRange(apdu, 5, apdu.length - 1);
            byte[] ct = Arrays.copyOf(body, body.length - 8);
            byte[] tag = Arrays.copyOfRange(body, body.length - 8, body.length);
            byte[] expected = Arrays.copyOf(H3.cmac(kcm, H3.cat(H3.u16(ctr), ct)), 8);
            // §8.3 steps 2–5: accepted only with P1 = P2 = 0, Lc ≥ 24, ct a 16-multiple,
            // the right tag and valid M2 padding
            boolean headerOk =
                    apdu[2] == 0 && apdu[3] == 0 && body.length >= 24 && (ct.length & 0xF) == 0;
            boolean tagOk = headerOk && H3.equal(expected, tag);
            byte[] iv = H3.aesBlock(kce, H3.cat(new byte[] {1}, H3.zeros(13), H3.u16(ctr)));
            boolean padOk = tagOk && H3.unM2(H3.cbcDec(kce, iv, ct)) != null;
            assertFalse(tagOk && padOk, "rejected command accepted: " + c.get("name"));
        }
        for (Map<String, Object> r : list(d, "rejectedResponses")) {
            int ctr = ((Number) r.get("ctr")).intValue();
            // §8.4: the host accepts a response only when tag AND padding check out
            byte[] rapdu = h(r.get("rapdu"));
            byte[] body = Arrays.copyOf(rapdu, rapdu.length - 2);
            byte[] ct = Arrays.copyOf(body, body.length - 8);
            byte[] tag = Arrays.copyOfRange(body, body.length - 8, body.length);
            byte[] expected = Arrays.copyOf(H3.cmac(krm, H3.cat(H3.u16(ctr), ct)), 8);
            boolean tagOk = ct.length >= 16 && H3.equal(expected, tag);
            byte[] iv = H3.aesBlock(kre, H3.cat(new byte[] {2}, H3.zeros(13), H3.u16(ctr)));
            boolean padOk =
                    ct.length >= 16
                            && (ct.length & 0xF) == 0
                            && H3.unM2(H3.cbcDec(kre, iv, ct)) != null;
            assertFalse(tagOk && padOk, "rejected response accepted: " + r.get("name"));
        }
    }

